// Draw a glyph onto a 2D canvas context, fitted to the canvas with padding.
export function drawGlyph(ctx, glyph, color, lineWidth = 3) {
  const { width:w, height:h } = ctx.canvas;
  ctx.clearRect(0, 0, w, h);
  const pad = Math.min(w, h) * 0.2;
  const s = (Math.min(w, h) - pad * 2) / 2;
  ctx.save();
  ctx.translate(w / 2, h / 2);
  ctx.strokeStyle = color;
  ctx.lineWidth = lineWidth;
  ctx.lineCap = 'round';
  ctx.lineJoin = 'round';
  ctx.shadowColor = color;
  ctx.shadowBlur = 10;
  for (const [a, b] of glyph.strokes) {
    ctx.beginPath();
    ctx.moveTo(a[0] * s, -a[1] * s);
    ctx.lineTo(b[0] * s, -b[1] * s);
    ctx.stroke();
  }
  ctx.restore();
}
